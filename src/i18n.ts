export type MessageKey = keyof typeof zh
export const locale = navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en"
const messages = locale === "zh-CN" ? zh : en

export function t(key: MessageKey): string {
  return messages[key]
}

function setMeta(selector: string, content: string) {
  document.querySelector<HTMLMetaElement>(selector)?.setAttribute("content", content)
}

export function applyDocumentLocale() {
  document.documentElement.lang = locale
  document.title = t("seo.title")

  for (const element of document.querySelectorAll<HTMLElement>("[data-i18n]")) {
    element.textContent = t(element.dataset.i18n as MessageKey)
  }
  for (const element of document.querySelectorAll<HTMLElement>("[data-i18n-placeholder]")) {
    element.setAttribute("placeholder", t(element.dataset.i18nPlaceholder as MessageKey))
  }
  for (const element of document.querySelectorAll<HTMLElement>("[data-i18n-alt]")) {
    element.setAttribute("alt", t(element.dataset.i18nAlt as MessageKey))
  }
  for (const element of document.querySelectorAll<HTMLElement>("[data-i18n-aria-label]")) {
    element.setAttribute("aria-label", t(element.dataset.i18nAriaLabel as MessageKey))
    element.setAttribute("title", t(element.dataset.i18nAriaLabel as MessageKey))
  }

  setMeta('meta[name="description"]', t("seo.description"))
  setMeta('meta[name="keywords"]', t("seo.keywords"))
  setMeta('meta[property="og:locale"]', locale === "zh-CN" ? "zh_CN" : "en_US")
  setMeta('meta[property="og:site_name"]', t("brand.name"))
  setMeta('meta[property="og:title"]', t("seo.title"))
  setMeta('meta[property="og:description"]', t("seo.shortDescription"))
  setMeta('meta[property="og:image:alt"]', t("seo.logoAlt"))
  setMeta('meta[name="twitter:title"]', t("seo.title"))
  setMeta('meta[name="twitter:description"]', t("seo.shortDescription"))
  document.querySelector<HTMLLinkElement>('link[rel="manifest"]')?.setAttribute(
    "href",
    locale === "zh-CN" ? "/site.webmanifest" : "/site-en.webmanifest",
  )

  const structuredData = document.querySelector<HTMLScriptElement>("#structured-data")
  if (structuredData) {
    structuredData.textContent = JSON.stringify({
      "@context": "https://schema.org",
      "@type": "VideoGame",
      name: t("brand.name"),
      alternateName: t("seo.title"),
      description: t("seo.description"),
      keywords: t("seo.keywords"),
      genre: locale === "zh-CN" ? ["打字游戏", "教育游戏"] : ["Fun typing games", "Typing game", "Educational game"],
      gamePlatform: locale === "zh-CN" ? "网页浏览器" : "Web browser",
      playMode: "SinglePlayer",
      applicationCategory: "GameApplication",
      operatingSystem: "Any",
      inLanguage: locale,
      isAccessibleForFree: true,
    })
  }
}
